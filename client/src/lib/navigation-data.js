export function getAllNavigationLinks() {
  const links = [];
  menuGroups.forEach((group) => {
    group.data.sections.forEach((section) => {
      section.links.forEach((item) => links.push({ ...item, category: section.title }));
    });
  });
  moreMenu.forEach((item) => links.push({ ...item, category: "More" }));
  Object.values(footerLinks).forEach((items) => {
    items.forEach((item) => links.push({ ...item, category: "Footer" }));
  });
  return uniqueLinks(links);
}

export function getServiceInfoBySlug(slug) {
  const normalized = `/${slug}`;
  return getAllNavigationLinks().find((item) => item.href === normalized);
}

export function getAllServiceRoutes() {
  return Array.from(new Set(getAllNavigationLinks().map((item) => item.href).filter(Boolean)));
}

