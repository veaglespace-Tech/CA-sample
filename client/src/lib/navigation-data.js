function slugify(label) {
  return String(label)
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/\|/g, " ")
    .replace(/\[[^\]]*\]/g, "")
    .replace(/\([^)]*\)/g, " ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function link(label, href, extra = {}) {
  return { label, href: href || routeOverrides[label] || `/${slugify(label)}`, ...extra };
}

function uniqueLinks(links) {
  const seen = new Set();
  return links.filter((item) => {
    const key = item.href || item.label;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

